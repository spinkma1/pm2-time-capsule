package cz.cvut.fel.pm2.enums;

/**
 * Enumeration representing different user roles.
 */
public enum Role {
    /**
     * Role for registered users.
     */
    ROLE_REGISTERED,

    /**
     * Role for administrators.
     */
    ROLE_ADMIN,

    /**
     * Role for premium users.
     */
    ROLE_PREMIUM,

    /**
     * Role for banned users.
     */
    ROLE_BANNED,

    /**
     * Role for deleted users.
     */
    ROLE_DELETED
}
