/**
 * Enumeration representing different types of notifications.
 */
public enum NotificationTypes {
    /**
     * Notification type for new access.
     */
    NEW_ACCESS,

    /**
     * Notification type for reminders.
     */
    REMINDER,

    /**
     * Notification type for opened capsules.
     */
    OPENED
}
